
// Clase que representa un nodo de la lista simplemente enlazada
public class Nodo {

    // Dato que almacena el nodo
    int dato;

    // Referencia al siguiente nodo de la lista
    Nodo siguiente;

    // Constructor: inicializa el nodo con un dato
    public Nodo(int dato) {
        this.dato = dato;
        this.siguiente = null;
    }
}
